#!/usr/bin/env python3
"""Build an offline video player (index.html) for the videos in a folder.

Copy this script into any folder that contains videos and run it. Videos in
sub-folders become menu groups. A <video>.wave.js waveform file is written
for every video into the resources folder (needs ffmpeg), and index.html
shows the videos in a sidebar menu with a player, a clickable waveform and
progress tracking. Waveform files left next to the videos by older versions
are moved into resources.

Usage:
    python3 update.py [folder] [--no-waveform] [--rebuild-waveforms]
                      [--jobs N] [--overwrite]
"""
import argparse
import array
import base64
import hashlib
import json
import math
import operator
import os
import re
import shutil
import subprocess
import sys
import time
from collections import Counter
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

VIDEO_EXTENSIONS = {".mp4", ".m4v", ".webm", ".mkv", ".mov", ".ogv"}
SKIPPED_DIR_PREFIXES = (".", "@", "#")
INDEX_NAME = "index.html"
RESOURCE_DIR = "resources"
GENERATOR_MARK = "<!-- generated by update.py: offline video index -->"

SAMPLE_RATE = 8000
WINDOW_SECONDS = 0.1
MIN_DB = -60.0


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("folder", nargs="?",
                        help="video folder (default: this script's folder)")
    parser.add_argument("--no-waveform", action="store_true",
                        help="do not generate waveform files")
    parser.add_argument("--rebuild-waveforms", action="store_true",
                        help="regenerate existing waveform files too")
    parser.add_argument("--jobs", type=int, default=2,
                        help="parallel ffmpeg processes (default: 2)")
    parser.add_argument("--overwrite", action="store_true",
                        help="replace an index.html not made by this script")
    return parser.parse_args()


# ---- Finding videos and naming them

def natural_key(text):
    return [
        int(part) if part.isdigit() else part.lower()
        for part in re.split(r"(\d+)", text)
    ]


def find_videos(root):
    videos = []
    for directory, subdirectories, files in os.walk(root):
        subdirectories[:] = [
            name for name in subdirectories
            if not name.startswith(SKIPPED_DIR_PREFIXES)
            and not (Path(directory) == root and name == RESOURCE_DIR)
        ]
        videos += [
            Path(directory, name) for name in files
            if Path(name).suffix.lower() in VIDEO_EXTENSIONS
            and not name.startswith(".")
        ]
    return sorted(
        videos,
        key=lambda video: [
            natural_key(part) for part in video.relative_to(root).parts
        ],
    )


def readable_title(file_stem):
    title = re.sub(r"[._]+", " ", file_stem)
    return re.sub(r"\s+", " ", title).strip(" -–")


def strip_common_suffix(titles):
    """Drop a trailing phrase (like a channel name) most titles share."""
    endings = Counter(
        " ".join(words[-length:])
        for words in map(str.split, titles)
        for length in (2, 3, 4)
        if len(words) > length
    )
    threshold = max(3, math.ceil(len(titles) / 2))
    common = [phrase for phrase, count in endings.items()
              if count >= threshold and re.search(r"[^\W\d_]", phrase)]
    if not common:
        return titles
    suffix = max(common, key=len)
    return [
        title[:-len(suffix)].strip(" -–") if title.endswith(suffix)
        else title
        for title in titles
    ]


def wave_paths(root, videos, folder):
    """<name>.wave.js for each video in folder, mirroring its sub-folder
    (<name.ext>.wave.js on clashes)."""
    paths, used = {}, set()
    for video in videos:
        directory = folder / video.parent.relative_to(root)
        path = directory / (video.stem + ".wave.js")
        if path in used:
            path = directory / (video.name + ".wave.js")
        used.add(path)
        paths[video] = path
    return paths


def move_old_waves(old_waves, waves):
    """Move waveform files from next to the videos into resources."""
    moved = 0
    for video, old in old_waves.items():
        if not old.is_file():
            continue
        new = waves[video]
        if new.exists():
            old.unlink()
        else:
            new.parent.mkdir(parents=True, exist_ok=True)
            os.replace(old, new)
            moved += 1
    if moved:
        print(f"Moved {moved} waveform files into {RESOURCE_DIR}/")


# ---- Waveform data

def to_level(amplitude):
    db = 20 * math.log10(max(amplitude, 1e-6) / 32768.0)
    return int(min(255, max(0, (db - MIN_DB) / (0 - MIN_DB) * 255)))


def decode_levels(video):
    """Peak and RMS level (0-255) of every 100 ms window of the audio."""
    window = int(SAMPLE_RATE * WINDOW_SECONDS)
    command = [
        "ffmpeg", "-v", "error", "-nostdin", "-i", str(video),
        "-vn", "-ac", "1", "-ar", str(SAMPLE_RATE), "-f", "s16le", "-",
    ]
    peaks, rms = bytearray(), bytearray()

    def add_block(block):
        peaks.append(to_level(max(map(abs, block))))
        power = sum(map(operator.mul, block, block)) / len(block)
        rms.append(to_level(math.sqrt(power)))

    pending = b""
    block_bytes = window * 2
    with subprocess.Popen(command, stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE) as process:
        while chunk := process.stdout.read(block_bytes * 1024):
            pending += chunk
            usable = len(pending) // block_bytes * block_bytes
            samples = array.array("h", pending[:usable])
            if sys.byteorder == "big":
                samples.byteswap()
            pending = pending[usable:]
            for start in range(0, len(samples), window):
                add_block(samples[start:start + window])
        error = process.stderr.read().decode(errors="replace").strip()

    if process.returncode != 0 and not peaks:
        raise RuntimeError(f"ffmpeg error: {error[-200:]}")
    tail = array.array("h", pending[:len(pending) // 2 * 2])
    if len(tail) >= window // 4:
        add_block(tail)
    if not peaks:
        raise RuntimeError("no audio track")
    return bytes(peaks), bytes(rms)


def write_wave(video, target):
    peaks, rms = decode_levels(video)
    data = {
        "sr": round(1 / WINDOW_SECONDS),
        "n": len(peaks),
        "dur": round(len(peaks) * WINDOW_SECONDS, 1),
        "peak": base64.b64encode(peaks).decode(),
        "rms": base64.b64encode(rms).decode(),
    }
    payload = json.dumps(data, separators=(",", ":"))
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(target.name + ".tmp")
    temporary.write_text(f"window.__wave&&window.__wave({payload});\n",
                         encoding="utf-8")
    os.replace(temporary, target)
    return f"{data['dur'] / 60:.1f} min"


def needs_wave(video, wave):
    return (not wave.exists()
            or wave.stat().st_mtime < video.stat().st_mtime
            or wave.stat().st_size < 50)


def generate_waveforms(waves, jobs, rebuild):
    if not shutil.which("ffmpeg"):
        print("ffmpeg not found: waveform files were not generated.")
        return
    pending = [(video, wave) for video, wave in waves.items()
               if rebuild or needs_wave(video, wave)]
    print(f"Waveform data needed for {len(pending)} of {len(waves)} videos "
          "(each video is read once; long ones take a few minutes)",
          flush=True)

    def work(pair):
        video, wave = pair
        print(f"   working on {video.name}", flush=True)
        started = time.time()
        try:
            message = write_wave(video, wave)
        except (OSError, RuntimeError) as error:
            return video, False, str(error)
        return video, True, f"{message}, took {time.time() - started:.0f} s"

    started = time.time()
    with ThreadPoolExecutor(jobs) as pool:
        futures = [pool.submit(work, pair) for pair in pending]
        for number, future in enumerate(as_completed(futures), 1):
            video, ok, message = future.result()
            status = "OK   " if ok else "ERROR"
            print(f"   [{number}/{len(pending)}] {status} {video.name}"
                  f" - {message}", flush=True)
    print(f"Waveforms done in {(time.time() - started) / 60:.1f} min")


# ---- index.html

def build_data(root, videos, waves):
    titles = strip_common_suffix(
        [readable_title(video.stem) for video in videos]
    )
    groups = {}
    for video, title in zip(videos, titles):
        relative = video.relative_to(root)
        group = " / ".join(relative.parent.parts)
        groups.setdefault(group, []).append({
            "id": relative.as_posix(),
            "title": title,
            "name": video.name,
            "path": relative.as_posix(),
            "wave": waves[video].relative_to(root).as_posix(),
            "size": video.stat().st_size,
        })
    path_hash = hashlib.sha1(str(root).encode()).hexdigest()[:10]
    return {
        "title": root.name.replace("_", " "),
        "storageKey": f"videoindex_{path_hash}_",
        "groups": [
            {"title": title, "videos": entries}
            for title, entries in groups.items()
        ],
    }


def write_index(root, data, overwrite):
    target = root / INDEX_NAME
    if target.exists() and not overwrite:
        existing = target.read_text(encoding="utf-8", errors="ignore")
        if GENERATOR_MARK not in existing:
            sys.exit(f"{target} was not made by this script; "
                     "use --overwrite to replace it.")
    payload = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    target.write_text(PAGE_TEMPLATE.replace("__DATA__", payload),
                      encoding="utf-8")
    return target


def main():
    args = parse_args()
    root = Path(args.folder or Path(__file__).parent).resolve()
    videos = find_videos(root)
    if not videos:
        sys.exit(f"No videos found in {root}")
    print(f"{len(videos)} videos in {root}")

    waves = wave_paths(root, videos, root / RESOURCE_DIR)
    move_old_waves(wave_paths(root, videos, root), waves)
    index = write_index(root, build_data(root, videos, waves),
                        args.overwrite)
    print(f"Written: {index}")
    if not args.no_waveform:
        generate_waveforms(waves, args.jobs, args.rebuild_waveforms)


